function normalizeLabel(value: string): string {
  return value.replace(/&/g, " and ").replace(/\s+/g, " ").trim().toLowerCase();
}

const normalizedLabels = new Map(Object.entries(labels).map(([key, value]) => [normalizeLabel(key), value]));

export function ukrainianInterviewLabel(value: string): string {
  return normalizedLabels.get(normalizeLabel(value)) ?? value;
}
